/**
 * Районы города. У Петербурга и Москвы настоящие, у остальных — части города относительно центра.
 * Точный адрес пользователя не храним: для поиска по радиусу хватает района.
 */
export function cityAreas(cityName: string): Record<string, LatLng> {
  if (cityName === 'Санкт-Петербург') return SPB_AREAS;
  if (cityName === 'Москва') return MOSCOW_AREAS;
  const city = cityByName(cityName);
  if (!city) return {};
  const [a, b] = city.center;
  const dy = 0.035;
  const dx = 0.06;
  return {
    'Центр': [a, b],
    'Север': [a + dy, b],
    'Юг': [a - dy, b],
    'Запад': [a, b - dx],
    'Восток': [a, b + dx],
    'Северо-запад': [a + dy * 0.7, b - dx * 0.7],
    'Северо-восток': [a + dy * 0.7, b + dx * 0.7],
    'Юго-запад': [a - dy * 0.7, b - dx * 0.7],
    'Юго-восток': [a - dy * 0.7, b + dx * 0.7],
  };
}

export const isArea = (city: string, area: unknown): area is string => typeof area === 'string' && area in cityAreas(city);

export function areaLabel(city: string, area: string): string {
  if (city === 'Санкт-Петербург') return `${area} район`;
  if (city === 'Москва') return area;
  return area === 'Центр' ? 'Центр города' : `${area} города`;
}

export function nearestCity(pt: LatLng): { city: City; km: number } {
  let best = CITIES[0]!;
  let bestKm = Infinity;
  for (const c of CITIES) {
    const km = haversineKm(pt, c.center);
    if (km < bestKm) [best, bestKm] = [c, km];
  }
  return { city: best, km: bestKm };
}

export function nearestArea(cityName: string, pt: LatLng): { name: string; km: number } | null {
  let best: string | null = null;
  let bestKm = Infinity;
  for (const [name, c] of Object.entries(cityAreas(cityName))) {
    const km = haversineKm(pt, c);
    if (km < bestKm) [best, bestKm] = [name, km];
  }
  return best ? { name: best, km: bestKm } : null;
}
